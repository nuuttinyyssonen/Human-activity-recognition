import numpy as np


def write_test_cases(clf, X_test, y_test, F_test, path,
                     n_per_class=3, n_wrong=6, seed=0):
    """Export test windows plus Python's predictions to a C++ header."""
    rng = np.random.default_rng(seed)
    classes = list(clf.classes_)
    y_pred = clf.predict(F_test)

    # n_per_class random windows from every class
    chosen = []
    for c in classes:
        idx = np.where(y_test == c)[0]
        chosen += rng.choice(idx, size=n_per_class, replace=False).tolist()

    # plus some windows the tree gets wrong (they exercise other branches)
    wrong = np.where(y_pred != y_test)[0]
    extra = [int(i) for i in rng.permutation(wrong) if int(i) not in chosen]
    chosen += extra[:n_wrong]

    true_idx = ", ".join(str(classes.index(y_test[i])) for i in chosen)
    pred_idx = ", ".join(str(classes.index(y_pred[i])) for i in chosen)
    n, w, c = len(chosen), X_test.shape[1], X_test.shape[2]

    lines = [
        "// Auto-generated by training/test_cases.py - do not edit by hand",
        "#pragma once",
        "",
        f"const int N_TESTS = {n};",
        f"const int TRUE_LABEL[N_TESTS] = {{{true_idx}}};",
        f"const int PY_PRED[N_TESTS] = {{{pred_idx}}};",
        "",
        f"const float TEST_WINDOWS[N_TESTS][{w}][{c}] = {{",
    ]
    for i in chosen:
        lines.append("  {")
        for row in X_test[i]:
            lines.append("    {" + ", ".join(f"{v:.6f}f" for v in row) + "},")
        lines.append("  },")
    lines.append("};")

    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {n} test windows to {path}")