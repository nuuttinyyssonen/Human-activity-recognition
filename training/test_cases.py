import numpy as np
from features import extract_features
from load_data import CHANNELS

def write_test_cases(clf, X_test, y_test, F_test, path,
                     n_per_class=3, n_wrong=6, seed=0):
    """Export test windows plus Python's predictions to a C++ header."""
    rng = np.random.default_rng(seed)
    classes = list(clf.classes_)
    y_pred = clf.predict(F_test)

    # n_per_class random windows from every class
    chosen = []
    for c in classes:
        idx = np.where(y_test == c)[0]
        chosen += rng.choice(idx, size=n_per_class, replace=False).tolist()

    # plus some windows the tree gets wrong (they exercise other branches)
    wrong = np.where(y_pred != y_test)[0]
    extra = [int(i) for i in rng.permutation(wrong) if int(i) not in chosen]
    chosen += extra[:n_wrong]

    true_idx = ", ".join(str(classes.index(y_test[i])) for i in chosen)
    pred_idx = ", ".join(str(classes.index(y_pred[i])) for i in chosen)
    n, w, c = len(chosen), X_test.shape[1], X_test.shape[2]

    lines = [
        "// Auto-generated by training/test_cases.py - do not edit by hand",
        "#pragma once",
        "",
        f"const int N_TESTS = {n};",
        f"const int TRUE_LABEL[N_TESTS] = {{{true_idx}}};",
        f"const int PY_PRED[N_TESTS] = {{{pred_idx}}};",
        "",
        f"const float TEST_WINDOWS[N_TESTS][{w}][{c}] = {{",
    ]
    for i in chosen:
        lines.append("  {")
        for row in X_test[i]:
            lines.append("    {" + ", ".join(f"{v:.6f}f" for v in row) + "},")
        lines.append("  },")
    lines.append("};")

    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {n} test windows to {path}")

def write_replay(clf, df, test_subjects, path,
                 seg_len=250, step=50, window=100, per_class=1, decimals=4):
    """Export recorded segments (one or more per class) and Python's predictions
    for each sliding window, using the same windowing as the firmware."""
    classes = list(clf.classes_)
    segments, expected = [], []

    for act in classes:
        g = df[(df.activity == act) & (df.subject.isin(test_subjects))]
        used_subjects = set()
        picked = 0
        # one recording per (subject, trial); prefer different subjects
        for (subj, trial), rec_df in g.groupby(["subject", "trial"]):
            if picked == per_class:
                break
            if subj in used_subjects or len(rec_df) < seg_len:
                continue
            rec = np.round(rec_df[CHANNELS].to_numpy()[:seg_len], decimals)
            W = np.array([rec[s:s + window]
                          for s in range(0, seg_len - window + 1, step)])
            preds = clf.predict(extract_features(W))
            segments.append(rec)
            expected.append([classes.index(p) for p in preds])
            used_subjects.add(subj)
            picked += 1
        if picked < per_class:
            print(f"Warning: only found {picked} segment(s) for {act}")

    n_seg, n_win = len(segments), len(expected[0])
    exp_rows = ", ".join("{" + ", ".join(map(str, e)) + "}" for e in expected)

    lines = [
        "// Auto-generated by training/replay.py - do not edit by hand",
        "#pragma once",
        f"const int N_SEG = {n_seg};",
        f"const int SEG_LEN = {seg_len};",
        f"const int N_WIN = {n_win};",
        f"const int EXPECTED[N_SEG][N_WIN] = {{{exp_rows}}};",
        "const float REPLAY[N_SEG * SEG_LEN][6] = {",
    ]
    for rec in segments:
        for row in rec:
            lines.append("  {" + ", ".join(f"{v:.{decimals}f}f" for v in row) + "},")
    lines.append("};")

    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {n_seg} segments x {n_win} windows to {path}")